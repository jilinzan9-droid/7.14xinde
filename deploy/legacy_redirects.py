#!/usr/bin/env python3
"""Build explicit Nginx redirects for reviewed, retired website URLs."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PREFIX = '/demo/pratt-oil-oilfield'
OUTPUT = 'deploy/nginx-legacy-redirects.conf'


def local_file(root, path):
    candidate = root / path.lstrip('/')
    if path.endswith('/'):
        candidate /= 'index.html'
    return candidate


def safe_path(path):
    return (isinstance(path, str) and path.startswith('/') and not path.startswith('//')
            and not any(x in path for x in ('..', '\\', '"', '$', ';', '#', '?', '%'))
            and not re.search(r'[\x00-\x20\x7f]', path))


def expanded_routes(root=ROOT):
    records = json.loads((root / 'deploy/legacy-redirects.json').read_text('utf-8'))['routes']
    result = {}
    for record in records:
        source, target = record['source'], record['target']
        if not safe_path(source) or not safe_path(target):
            raise ValueError(f'Unsafe redirect path: {source!r} -> {target!r}')
        if source == target or not local_file(root, target).is_file():
            raise ValueError(f'Redirect destination is missing or self-referential: {source} -> {target}')
        if local_file(root, source).is_file():
            raise ValueError(f'Redirect would replace an existing file: {source}')
        variants = {source}
        if source.endswith('/'):
            variants.update({source[:-1], source + 'index.html'})
        if not source.startswith(PREFIX):
            variants.update({PREFIX + item for item in list(variants)})
        for variant in variants:
            if variant in result and result[variant] != target:
                raise ValueError(f'Conflicting redirect: {variant}')
            result[variant] = target
    lower = {}
    for source, target in result.items():
        # Nginx map string keys are case insensitive.
        if source.lower() in lower and lower[source.lower()] != target:
            raise ValueError(f'Case-insensitive map collision: {source}')
        lower[source.lower()] = target
        if target in result:
            raise ValueError(f'Redirect chain or cycle: {source} -> {target}')
    return result


def render(root=ROOT):
    entries = expanded_routes(root)
    lines = ['# Generated by deploy/legacy_redirects.py. Install in /etc/nginx/conf.d/.',
             '# Exact paths only. Unrecognized URLs retain their genuine 404 status.',
             'map_hash_bucket_size 512;', 'map_hash_max_size 8192;',
             'map $uri $pratt_legacy_redirect {', '    default "";']
    lines += [f'    "{source}" "{target}";' for source, target in sorted(entries.items())]
    return '\n'.join(lines + ['}', ''])


def validate(root=ROOT):
    expected = render(root)
    if (root / OUTPUT).read_text('utf-8') != expected:
        raise ValueError('Legacy redirect config is stale; run python deploy/legacy_redirects.py')
    return len(expanded_routes(root))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        print(f'Validated {validate()} exact historical redirect variants.')
    else:
        (ROOT / OUTPUT).write_text(render(), encoding='utf-8', newline='\n')
        print(f'Generated {len(expanded_routes())} exact historical redirect variants.')
